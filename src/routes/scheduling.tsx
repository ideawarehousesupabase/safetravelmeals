import { createFileRoute, Link } from "@tanstack/react-router";
import { SiteShell, PageHeader } from "@/components/site-shell";
import { JaapNav, Pill, SetBadge, SimulatedBanner } from "@/components/jaap/jaap-ui";
import { Plane, Hotel, Briefcase, ArrowRight, ListChecks, FileText } from "lucide-react";
import { DEMO, FEATURED_IDS, journeyById, kitById } from "@/lib/jaap/demo";
import { DISHES, RULE_SET_VERSION, WINDOW_TYPES } from "@/lib/jaap/protocol";
import { fmtDT, fmtRange, toMin } from "@/lib/jaap/time";

export const Route = createFileRoute("/scheduling")({
  head: () => ({
    meta: [
      { title: "Meal Plan — SafeMeal" },
      { name: "description", content: "A mapped journey's exposure windows, production runs and handovers." },
    ],
  }),
  component: SchedulingPage,
});

const ICON = { late_arrival: Hotel, breakfast: Hotel, lunch: Briefcase, in_transit: Plane };

function SchedulingPage() {
  const j = journeyById(FEATURED_IDS.business)!;
  const recent = j.kitIds
    .flatMap((id) => kitById(id)!.ledger)
    .filter((e) => e.event !== "Exposure window confirmed" && e.event !== "Assigned to production run")
    .sort((a, b) => toMin(b.ts) - toMin(a.ts))
    .slice(0, 5);
  const runs = [...new Set(j.kitIds.map((id) => kitById(id)!.runId))].map((id) => DEMO.runs.find((r) => r.id === id)!);

  return (
    <SiteShell>
      <PageHeader
        eyebrow="Meal plan · sample journey"
        title="Your itinerary, decoded into exposure windows."
        description={`${j.label}. ${j.windows.length} windows generated by ${RULE_SET_VERSION}, ${j.windows.filter((w) => w.accepted).length} confirmed by the traveller.`}
      >
        <SetBadge setId={j.set!.id} long />
      </PageHeader>
      <JaapNav />

      <div className="mx-auto max-w-7xl px-6 py-10 space-y-6">
        <SimulatedBanner />
        <div className="grid lg:grid-cols-3 gap-6">
          <div className="lg:col-span-2 rounded-3xl border border-brand-border bg-card p-6">
            <div className="flex items-center justify-between mb-6">
              <h2 className="font-display font-extrabold text-lg flex items-center gap-2">
                <ListChecks className="size-5 text-brand-accent" /> Exposure windows
              </h2>
              <Link to="/itinerary" search={{ journey: j.id }} className="text-sm font-bold text-brand-accent">Edit itinerary</Link>
            </div>

            <div className="relative pl-8 border-l-2 border-brand-accent/20 space-y-5">
              {j.windows.map((w) => {
                const Icon = ICON[w.type];
                const kit = w.kitIds[0] ? kitById(w.kitIds[0]) : undefined;
                const done = kit?.status === "Receipt confirmed";
                return (
                  <div key={w.key} className="relative">
                    <div className={`absolute -left-[37px] size-5 rounded-full grid place-items-center ${done ? "bg-brand-success" : "bg-card border-2 border-brand-border"}`}>
                      {done && <span className="text-white text-[10px]">✓</span>}
                    </div>
                    <div className={`rounded-2xl border p-4 ${w.accepted ? "border-brand-border" : "border-dashed border-brand-border opacity-70"}`}>
                      <div className="flex items-center justify-between mb-2">
                        <p className="text-xs font-bold text-brand-accent">{fmtRange(w.occasionStart, w.occasionEnd)}</p>
                        {w.accepted ? (
                          <Pill tone={done ? "ok" : "info"}>{kit?.status ?? "Planned"}</Pill>
                        ) : (
                          <Pill tone="info">Removed by traveller</Pill>
                        )}
                      </div>
                      <div className="flex items-start gap-3">
                        <div className="size-10 rounded-xl bg-brand-accent/10 grid place-items-center text-brand-accent">
                          <Icon className="size-4" />
                        </div>
                        <div className="flex-1">
                          <p className="font-semibold">{w.ruleId} · {WINDOW_TYPES[w.type].label}: {DISHES[j.preference][w.type]}</p>
                          <p className="text-xs text-muted-foreground mt-0.5">{w.place}</p>
                          <p className="text-xs mt-1">{w.reason}</p>
                          {kit && (
                            <Link to="/records/$kitId" params={{ kitId: kit.id }} className="mt-2 inline-block text-xs font-bold text-brand-accent">
                              {kit.id} · {kit.runId} · seal {kit.sealNo} →
                            </Link>
                          )}
                          {!w.accepted && <p className="text-xs text-muted-foreground mt-1">{w.declineReason}</p>}
                        </div>
                      </div>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>

          <aside className="space-y-6">
            <div className="rounded-2xl bg-gradient-to-br from-brand-primary to-slate-800 text-white p-6">
              <h3 className="font-display font-extrabold text-lg">How the plan was built</h3>
              <ul className="mt-4 space-y-3 text-sm">
                {[
                  "Deterministic mapping rules, with the rule-set version recorded against the plan",
                  `Kits grouped into a single-allergen run: ${runs.map((r) => r.id).join(", ")}`,
                  `${j.batches.length} handovers inside declared windows`,
                  "If a flight moves, affected windows are regenerated (year 1 build)",
                ].map((f) => (
                  <li key={f} className="flex items-start gap-2">
                    <span className="size-1.5 rounded-full bg-brand-accent mt-1.5 shrink-0" />
                    <span className="text-white/80">{f}</span>
                  </li>
                ))}
              </ul>
            </div>

            <div className="rounded-2xl border border-brand-border bg-card p-6">
              <h3 className="font-display font-extrabold mb-4">Latest record entries</h3>
              <ul className="space-y-3 text-sm">
                {recent.map((e) => (
                  <li key={`${e.kitId}-${e.seq}`} className="flex items-start gap-3">
                    <FileText className={`size-4 mt-0.5 shrink-0 ${e.data.exception ? "text-amber-600" : "text-brand-accent"}`} />
                    <div>
                      <p className="font-semibold">{e.event}</p>
                      <p className="text-xs text-muted-foreground">{e.kitId} · {fmtDT(e.ts)}</p>
                    </div>
                  </li>
                ))}
              </ul>
            </div>

            <Link to="/checkout" className="block rounded-2xl bg-brand-accent text-white p-6 hover:scale-[1.02] transition-transform shadow-glow">
              <p className="text-xs font-bold uppercase tracking-widest text-white/70">{j.productInfo?.name}</p>
              <p className="font-display text-3xl font-extrabold mt-1">{j.productInfo?.price}</p>
              <p className="mt-3 text-sm font-bold flex items-center gap-1">Review plan <ArrowRight className="size-4" /></p>
            </Link>
          </aside>
        </div>
      </div>
    </SiteShell>
  );
}
